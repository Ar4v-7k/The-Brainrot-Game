MAP = [
    "##############################",
    "#............~~~~............#",
    "#..gggg......~~~~......ggg...#",
    "#..gggg.................gg...#",
    "#..........######............#",
    "#..ggg.....#....#.....gggg...#",
    "#..ggg.....#....#.....gggg...#",
    "#..........#....#............#",
    "#..........######............#",
    "#....ffff............ffff....#",
    "#....fggf............fggf....#",
    "#....ffff....gggg....ffff....#",
    "#............gggg............#",
    "#..gggg...............gggg...#",
    "#..gggg......~~~~.....gggg...#",
    "#............~~~~............#",
    "#............................#",
    "##############################",
]

WALKABLE = {".", "g", "f"}
GRASS = {"g"}


def tile_at(x: int, y: int) -> str:
    if y < 0 or y >= len(MAP) or x < 0 or x >= len(MAP[0]):
        return "#"
    return MAP[y][x]


def is_walkable(x: int, y: int) -> bool:
    return tile_at(x, y) in WALKABLE


def is_grass(x: int, y: int) -> bool:
    return tile_at(x, y) in GRASS
